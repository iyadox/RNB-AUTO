import { chromium } from "@playwright/test";
const out = process.argv[2];
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
page.on("console", (m) => { if (m.type() === "error") errors.push(m.text()); });
await page.goto("http://localhost:3000/demande", { waitUntil: "networkidle" });
await page.waitForTimeout(800);
const shot = async (name) => { await page.waitForTimeout(700); await page.screenshot({ path: `${out}/flow-${name}.png` }); };
await page.getByLabel("Adresse où se trouve le véhicule").fill("12 rue Hoche, Pantin");
await page.waitForSelector("[role=option]", { timeout: 8000 });
await shot("1-suggestions");
await page.locator("[role=option]").first().click();
await page.getByRole("button", { name: "Non", exact: true }).click();
await shot("1b-pickup");
await page.getByRole("button", { name: "Continuer" }).click();
await page.getByLabel("Destination du véhicule").fill("Paris 11e");
await page.waitForSelector("[role=option]");
await page.locator("[role=option]").first().click();
await shot("2-dropoff");
await page.getByRole("button", { name: "Continuer" }).click();
await shot("3-vehicle");
await page.getByRole("button", { name: /Berline/ }).click();
await page.getByRole("button", { name: /Panne mécanique/ }).click();
await page.getByRole("button", { name: "Non", exact: true }).click();
await shot("4-problem");
await page.getByRole("button", { name: /Voir le prix/ }).click();
await page.waitForSelector("text=Prix estimé", { timeout: 15000 });
await page.waitForTimeout(1200);
await shot("5-estimate");
await page.getByRole("button", { name: /Demander le dépannage/ }).click();
await page.getByPlaceholder("Votre nom").fill("Test Client");
await page.getByPlaceholder("06 12 34 56 78").fill("06 12 34 56 78");
await page.locator("input[type=checkbox]").last().check();
await page.waitForTimeout(2600);
await shot("6-contact");
await page.getByRole("button", { name: /Envoyer ma demande/ }).click();
await page.waitForSelector("text=Demande reçue", { timeout: 15000 });
await shot("7-done");
console.log("errors:", errors.length ? errors.join("\n") : "none");
await browser.close();
